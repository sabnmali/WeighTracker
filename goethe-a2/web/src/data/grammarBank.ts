import type { Difficulty, Question, QuestionCategory, QuestionType } from '../types';

/**
 * Elle hazırlanmış Goethe A2 soru bankası.
 * Hata avı sorularında gerçek öğrenci hataları kullanılır (Real Learner Traps).
 */

interface Spec {
  id: string;
  q: string;
  tr: string;
  o: string[];
  a: string;
  ex: string;
  rule: string;
  trap?: string;
  d?: Difficulty;
  word?: string;
}

function build(category: QuestionCategory, type: QuestionType, specs: Spec[]): Question[] {
  return specs.map((s) => ({
    id: s.id,
    type,
    category,
    difficulty: s.d || 'A2.1',
    question: s.q,
    questionTr: s.tr,
    options: s.o,
    correctAnswer: s.a,
    explanation: s.ex,
    targetRule: s.rule,
    errorTrap: s.trap,
    targetWord: s.word,
    source: 'bank' as const,
  }));
}

